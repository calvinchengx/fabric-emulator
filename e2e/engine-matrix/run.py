#!/usr/bin/env python3
"""Run the capability probes against both Spark engines and generate the matrix.

Output is `docs/engine-matrix.md` — generated, not hand-written, because the
hand-written version drifted: a row claimed streaming failed on Sail long after
Sail gained streaming support, and three capabilities were bundled under one
verdict that hid a partial pass.

    ./run.py            run both engines and rewrite the matrix
    ./run.py --engine sail   run one engine only (leaves the other's results)
    ./run.py --check    fail if the generated matrix differs from the committed
                        one (CI mode: the matrix must be regenerated when the
                        engines change)
"""
import argparse
import json
import os
import pathlib
import subprocess
import sys

DIR = pathlib.Path(__file__).resolve().parent
OUT = DIR / "out"
MATRIX = DIR.parent.parent / "docs" / "engine-matrix.md"
COMPOSE = ["docker", "compose", "-f", str(DIR / "docker-compose.yml")]
ENGINES = ("sail", "sail-delta", "jvm")


def ensure_out_writable() -> None:
    """Make `out/` writable by whatever uid the probe containers run as.

    The JVM image is `apache/spark`, which drops to `USER spark` (uid 185). The
    bind-mounted `out/` is owned by the checkout user, so that probe ran all 19
    capabilities and then died on `PermissionError: '/out/jvm.json'` — after the
    measuring was done, which is the most wasteful place to fail.

    It passed on macOS throughout: Docker Desktop's filesystem ignores the uid
    mismatch, so only Linux CI ever saw it. That is why this job had never gone
    green despite the matrix regenerating cleanly on a laptop every time.

    The existing result files need chmod too, not just the directory. The
    directory bits govern create/delete/rename; `open(path, "w")` *truncates*
    an existing file, which needs write permission on that file. Since
    `out/*.json` are tracked, checkout recreates them 644 and owned by the
    runner, so a writable directory alone changes nothing — which is exactly
    how the first attempt at this fix failed.
    """
    OUT.mkdir(parents=True, exist_ok=True)
    os.chmod(OUT, 0o777)
    for existing in OUT.glob("*.json"):
        os.chmod(existing, 0o666)


def run_engine(engine: str) -> int:
    service = {"sail": "sail-probe", "sail-delta": "sail-delta-probe"}.get(engine, "jvm-probe")
    print(f"==> probing {engine}", flush=True)
    try:
        result = subprocess.run(
            COMPOSE + ["--profile", engine, "up", "--build",
                       "--abort-on-container-exit", "--exit-code-from", service])
        return result.returncode
    finally:
        subprocess.run(COMPOSE + ["--profile", engine, "down", "-v"],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def load(engine: str):
    path = OUT / f"{engine}.json"
    if not path.exists():
        raise SystemExit(f"no results for {engine}: {path} missing")
    return {r["id"]: r for r in json.loads(path.read_text())}


def cell(result) -> str:
    if result is None:
        return "—"
    if result["status"] == "pass":
        return "✅"
    err = result.get("error", "")
    # The message is the useful part: it says *why*, and different messages
    # point at different upstream fixes.
    return f"❌ `{err[:90]}`" if err else "❌"


